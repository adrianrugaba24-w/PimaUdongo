"""
A clearly-labelled SYNTHETIC stand-in for AfSIS Phase I, used ONLY because the
real files are not on this machine.  It exists to exercise the pipeline: the
numbers it produces are not results and must never be quoted as such.

What makes it a fair test of the machinery (and nothing more):

* sites sit in compact geographic regions, and the SOC - clay relationship is
  REGION-DEPENDENT (intercept and slope both shift with the region).  That is
  non-stationarity, the property that makes geographic generalisation hard, and
  it is put in deliberately so the validation design has something real to lose.
  Without it, random and spatial CV are indistinguishable by construction;
* SOC depends weakly on pH / clay / EC plus a spatially structured latent field,
  so the true relationship is real but modest by construction;
* every messiness case the cleaning pass must survive is injected on purpose:
  five depth increments per profile, two labs measuring overlapping sites,
  exact duplicate rows, missing coordinates, 0/0 placeholder coordinates,
  impossible values (clay > 100, negative pH, zero carbon), and ~15% missing
  feature values.

The generative constants are returned by `specification()` and written into
results.json, so nobody can mistake this output for a measurement.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

LABS = ("ICRAF", "CROPNUTS")
COUNTRIES = {                     # rough bounding boxes, East Africa + Nigeria
    "Kenya":     (-4.9, 5.5, 34.0, 41.9),
    "Uganda":    (-1.5, 4.3, 29.6, 35.0),
    "Tanzania":  (-11.0, -1.0, 29.3, 40.4),
    "Nigeria":   (4.3, 13.9, 2.8, 14.6),
}
DEPTH_BANDS = [(0, 5), (5, 15), (15, 30), (30, 60), (60, 100)]
DECAY = {0: 1.0, 1: 0.72, 2: 0.50, 3: 0.33, 4: 0.22}      # SOC falls with depth

# Injected data problems (counts, not probabilities - so they are checkable).
N_IMPOSSIBLE = dict(clay_over_100=6, negative_ph=4, zero_carbon=5, texture_sum=5)
N_COORD_PROBLEMS = dict(missing=8, placeholder_zero=4)
N_DUPLICATE_ROWS = 12        # exact repeats, injected into the surface band
N_MULTILAB_REPLICATES = 40   # same surface record measured by the other lab
MISSING_FRACTION = 0.15

# Written next to the generated CSVs so a stand-in directory can never be
# mistaken for the real AfSIS download - the experiment checks for this file
# before it is allowed to label its output as real data.
MARKER_NAME = "SYNTHETIC_STAND_IN.txt"
MARKER_TEXT = (
    "THIS IS NOT THE AfSIS DATASET.\n"
    "These CSV files were generated by synthetic_afsis.py in the PimaUdongo\n"
    "repository to test the pipeline. Every number computed from them describes\n"
    "a simulation, not African soils, and must not be cited or reported.\n"
    "Delete this marker only if you are replacing the files with a real download.\n")


def is_stand_in(root: str | Path) -> bool:
    """True if `root` was written by write_dataset (marker file present)."""
    return (Path(root) / MARKER_NAME).is_file()


def specification() -> dict:
    """The generative recipe, recorded next to any result that uses it."""
    return dict(
        kind="synthetic stand-in",
        real_data=False,
        labs=list(LABS),
        depth_bands_cm=[list(b) for b in DEPTH_BANDS],
        soc_decay_with_depth=list(DECAY.values()),
        countries=list(COUNTRIES),
        injected_problems=dict(impossible_values=N_IMPOSSIBLE,
                               coordinate_problems=N_COORD_PROBLEMS,
                               exact_duplicate_rows=N_DUPLICATE_ROWS,
                               multilab_replicates=N_MULTILAB_REPLICATES,
                               feature_missing_fraction=MISSING_FRACTION),
        true_model=("SOC = (1.90 + 0.55*a_r) + (0.22 + 0.18*b_r)*(clay-28)/10 "
                    "- 0.55*(EC-0.2) - 0.15*(pH-6.0) + N(0,0.35); a_r and b_r are "
                    "per-REGION draws and each region is a compact geographic "
                    "cluster, so the relationship is non-stationary in space. "
                    "clay also shifts with a_r, which lets a random split partly "
                    "recognise a region from its features."),
        designed_to_show=("a gap between random CV and spatially blocked CV. This "
                          "is a property of the simulation, chosen so the pipeline "
                          "can be tested; it is NOT a claim about African soils."),
        warning=("SYNTHETIC: numbers from this dataset describe a simulation, "
                 "not African soils. Do not cite."),
    )


def _regions(rng, n_sites, n_clusters):
    """
    Draw one region per site, one home country per region, and the two region
    effects that make the SOC-clay relationship non-stationary.
    """
    names = list(COUNTRIES)
    weights = np.array([0.30, 0.22, 0.28, 0.20])      # Uganda stays a real minority
    region = rng.integers(0, n_clusters, n_sites)
    region_country = rng.choice(names, n_clusters, p=weights)
    a = rng.normal(0.0, 1.0, n_clusters)      # shifts the SOC level
    b = rng.normal(0.0, 1.0, n_clusters)      # shifts the clay slope
    return region, region_country, a, b


def _coords(rng, region, region_country):
    """One compact centre per region, inside that region's own country box."""
    lat, lon = np.zeros(len(region)), np.zeros(len(region))
    centres = {}
    for k in np.unique(region):
        la0, la1, lo0, lo1 = COUNTRIES[region_country[k]]
        centres[int(k)] = (rng.uniform(la0 + 0.25 * (la1 - la0), la1 - 0.25 * (la1 - la0)),
                           rng.uniform(lo0 + 0.25 * (lo1 - lo0), lo1 - 0.25 * (lo1 - lo0)))
    for i, k in enumerate(region):
        la0, la1, lo0, lo1 = COUNTRIES[region_country[k]]
        cl, cn = centres[int(k)]
        # ~0.35 deg scatter = a tight locality, so a KMeans block can hold out
        # territory the model has never seen.
        lat[i] = np.clip(cl + rng.normal(0, 0.35), la0, la1)
        lon[i] = np.clip(cn + rng.normal(0, 0.35), lo0, lo1)
    return lat, lon


def build_frames(seed: int = 20261104, n_sites: int = 420, n_clusters: int = 14):
    """Return (georeferences_df, {lab: wet_chemistry_df})."""
    rng = np.random.default_rng(seed)

    site_id = np.arange(1, n_sites + 1)
    ssn = 100000 + site_id * 7                            # deterministic, unique
    profile_ids = [f"P{i:05d}" for i in site_id]
    site_ids = [f"S{i:04d}" for i in site_id]
    region, region_country, field_a, field_b = _regions(rng, n_sites, n_clusters)
    country = region_country[region]
    lat, lon = _coords(rng, region, region_country)

    # --- surface-layer properties, shared by every depth of the profile ------
    clay = np.clip(28 + 12 * field_a[region] + rng.normal(0, 9, n_sites), 2, 78)
    sand = np.clip(100 - clay - rng.uniform(8, 26, n_sites), 2, 92)
    silt = np.clip(100 - clay - sand, 1, 60)
    ec = np.clip(np.exp(rng.normal(-1.6, 0.7, n_sites)) * (1 + 0.02 * (clay - 28)), 0.01, 8)
    ph = np.clip(6.3 - 0.035 * (clay - 28) + rng.normal(0, 0.55, n_sites), 3.8, 9.2)

    intercept = 1.90 + 0.55 * field_a[region]
    slope_clay = 0.22 + 0.18 * field_b[region]

    rows = []
    for di, (top, base) in enumerate(DEPTH_BANDS):
        soc = np.clip(intercept + slope_clay * (clay - 28.0) / 10.0 - 0.55 * (ec - 0.2)
                      - 0.15 * (ph - 6.0) + rng.normal(0, 0.35, n_sites), 0.05, 12.0) \
            * DECAY[di]
        inc = np.clip(rng.uniform(0.0, 0.25, n_sites) * (base / 100.0), 0.0, 1.0)
        # Coordinates live ONLY in the georeference table, as in the real AfSIS
        # layout - duplicating them here would create Latitude_x/Latitude_y on merge.
        rows.append(pd.DataFrame(dict(
            SSN=ssn, Profile_ID=profile_ids, Site_ID=site_ids,
            Depth_From_cm=top, Depth_To_cm=base,
            **{"pH_H2O": ph, "EC": ec, "Clay percent": clay,
               "Sand percent": sand, "Silt percent": silt,
               "Total C": soc + inc, "Inorganic C": inc, "SOC": soc})))
    wet_all = pd.concat(rows, ignore_index=True)

    # --- split across two labs with a systematic lab bias + measurement noise -
    lab_assign = rng.random(len(wet_all)) < 0.55
    wet_all["lab"] = np.where(lab_assign, LABS[0], LABS[1])
    for lab, bias, jit in [(LABS[0], 0.00, 0.05), (LABS[1], 0.11, 0.09)]:
        m = wet_all["lab"] == lab
        wet_all.loc[m, "SOC"] = np.clip(wet_all.loc[m, "SOC"] + bias
                                        + rng.normal(0, jit, int(m.sum())), 0.02, 14)

    geo = pd.DataFrame(dict(SSN=ssn, Latitude=lat, Longitude=lon, Country=country))

    # --- inject the messiness the cleaning pass must report -------------------
    def _spoil(df):
        # positional indices below must match labels, so re-set the index first
        df = df.reset_index(drop=True).copy()
        idx = rng.permutation(len(df))
        c = N_IMPOSSIBLE["clay_over_100"]
        df.loc[idx[:c], "Clay percent"] = rng.uniform(105, 160, c)
        c += N_IMPOSSIBLE["negative_ph"]
        df.loc[idx[c - N_IMPOSSIBLE["negative_ph"]:c], "pH_H2O"] = rng.uniform(-2.0, -0.1,
                                                                              N_IMPOSSIBLE["negative_ph"])
        c += N_IMPOSSIBLE["zero_carbon"]
        df.loc[idx[c - N_IMPOSSIBLE["zero_carbon"]:c], "SOC"] = 0.0
        c += N_IMPOSSIBLE["texture_sum"]
        sel = idx[c - N_IMPOSSIBLE["texture_sum"]:c]
        df.loc[sel, "Clay percent"] = rng.uniform(70, 90, len(sel))
        df.loc[sel, "Sand percent"] = rng.uniform(40, 60, len(sel))
        for col in ("pH_H2O", "EC", "Clay percent", "Sand percent", "Silt percent"):
            hit = rng.random(len(df)) < MISSING_FRACTION / 5
            df.loc[hit, col] = np.nan
        return df

    out = {}
    for lab in LABS:
        out[lab] = _spoil(wet_all[wet_all["lab"] == lab])
    spoiled = pd.concat(out.values(), ignore_index=True)

    # Duplicates are injected into the SURFACE band only, so they survive the
    # 0-5 cm filter and actually exercise the deduplication ledger.
    surf = spoiled[spoiled["Depth_From_cm"] == DEPTH_BANDS[0][0]]
    dupes = surf.sample(min(N_DUPLICATE_ROWS, len(surf)), random_state=int(seed))
    n_rep = min(N_MULTILAB_REPLICATES, len(surf))
    rep = surf.sample(n_rep, random_state=int(seed) + 1).copy()
    rep["lab"] = np.where(rep["lab"] == LABS[0], LABS[1], LABS[0])
    rep["SOC"] = np.clip(rep["SOC"] + rng.normal(0.04, 0.08, n_rep), 0.02, 14)
    allrows = pd.concat([spoiled, dupes, rep], ignore_index=True)

    out = {lab: allrows[allrows["lab"] == lab].drop(columns="lab").reset_index(drop=True)
           for lab in LABS}

    # coordinate problems live in the georeference table
    geo = geo.copy()
    bad = rng.permutation(len(geo))
    geo.loc[bad[:N_COORD_PROBLEMS["missing"]], "Latitude"] = np.nan
    n0 = N_COORD_PROBLEMS["missing"]
    geo.loc[bad[n0:n0 + N_COORD_PROBLEMS["placeholder_zero"]], ["Latitude", "Longitude"]] = 0.0
    return geo, out


def write_dataset(root: str | Path, **kw) -> dict:
    """Write the stand-in in AfSIS folder layout; returns file counts."""
    root = Path(root)
    geo, labs = build_frames(**kw)
    (root / "Georeferences").mkdir(parents=True, exist_ok=True)
    geo.to_csv(root / "Georeferences" / "georeferences.csv", index=False)
    for lab, df in labs.items():
        d = root / "Wet_Chemistry" / lab
        d.mkdir(parents=True, exist_ok=True)
        df.to_csv(d / f"Wet_Chemistry_{lab}.csv", index=False)
    (root / MARKER_NAME).write_text(MARKER_TEXT)      # self-identifying output
    return dict(n_sites=int(len(geo)), n_wet_rows=int(sum(len(d) for d in labs.values())),
                labs=list(labs), marker=MARKER_NAME)
