def rmse(y, p) -> float:
    y, p = np.asarray(y, float), np.asarray(p, float)
    return float(np.sqrt(np.mean((y - p) ** 2)))


def classify_data_source(root, synthetic_flag: bool) -> tuple[str, bool, bool]:
    """
    Decide whether this run may be labelled real AfSIS data.

    Only that label can be cited, so the decision is made from evidence on disk
    rather than from a default: a stand-in written by synthetic_afsis.py carries
    its own marker file, and --synthetic lets a human declare any other
    directory fake.  A directory counts as real only when neither applies, and a
    missing root is never real (nothing was verified).
    Returns (kind, is_real_data, marker_found).
    """
    marker = bool(root) and S.is_stand_in(root)
    real_data = bool(root) and not (marker or synthetic_flag)
    return ("afsis_real" if real_data else "synthetic_stand_in"), real_data, marker


def _jsonable(o):
    # bool must be tested BEFORE int: bool is a subclass of int, so a boolean
    # would otherwise be written to JSON as 1/0 and lose its meaning.
    if isinstance(o, (np.bool_, bool)):
        return bool(o)
    if isinstance(o, (np.floating, float)):
        f = float(o)
        return None if not np.isfinite(f) else f
    if isinstance(o, (np.integer, int)):
        return int(o)
    if isinstance(o, np.ndarray):
        return [_jsonable(x) for x in o.tolist()]
    if isinstance(o, dict):
        return {str(k): _jsonable(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_jsonable(x) for x in o]
    return o


def _mode_params(rows, model, scheme):
    """
    Most frequently selected hyperparameters across folds/seeds.

    Returns the parameter dict with its ORIGINAL value types (an int stays an
    int), because it is fed back into set_params for the fixed-parameter runs.
    """
    votes: dict[tuple, list] = {}
    for r in rows:
        if r.get("model") != model or r.get("cv") != scheme or r.get("experiment") != "main":
            continue
        for fp in r.get("tuned_params", []):
            for fold_dict in fp:
                clean = {k: v for k, v in fold_dict.items() if k != "fold"}
                key = tuple(sorted((k, repr(v)) for k, v in clean.items()))
                if key not in votes:
                    votes[key] = [0, clean]
                votes[key][0] += 1
    if not votes:
        return None
    best_key = max(sorted(votes), key=lambda k: votes[k][0])
    return votes[best_key][1]


def _spread(rows, models, method, learner_seed, distinct, blocks):
    """
    Mean, SD and range of spatial R2 across the partitions in `rows`.

    One entry per model. `distinct` is the number of genuinely different
    partitions the blocking seeds produced (compared up to renumbering), so a
    reader can tell 'the estimate did not move' from 'the partition never moved'.
    """
    out = []
    for name in models:
        cells = sorted({int(r["block_seed"]): float(r["r2_mean"]) for r in rows
                        if r.get("model") == name and "r2_mean" in r
                        and np.isfinite(r["r2_mean"])}.items())
        if not cells:
            continue
        vals = np.array([c[1] for c in cells], float)
        out.append(dict(
            model=name, method=method, n_partitions=len(vals),
            partition_seeds=[int(c[0]) for c in cells],
            distinct_partitions=int(distinct), learner_seed=int(learner_seed),
            blocks=blocks, r2_mean=float(vals.mean()),
            r2_sd=float(vals.std(ddof=1)) if len(vals) > 1 else None,
            r2_min=float(vals.min()), r2_max=float(vals.max()),
            note=("only the partition varied here: same learner seed and the "
                  f"fixed parameters chosen in E1, so no model-randomness or "
                  f"tuning variance is mixed in. A 0.000 SD with "
                  f"{distinct} distinct partition(s) means the spatial R2 did "
                  f"not move when the boundaries moved.")))
    return out


def _tidy(rows: list[dict]) -> pd.DataFrame:
    recs = []
    for r in rows:
        if "error" in r:
            recs.append({k: v for k, v in r.items() if k != "per_seed"})
            continue
        agg = {k: v for k, v in r.items() if k not in ("per_seed", "tuned_params")}
        recs.append(dict(agg, seed=None))
        for ps in r.get("per_seed", []):
            recs.append(dict(agg, seed=ps["seed"],
                             **{f"{m}_seed": ps[m] for m in ("r2", "rmse", "mae", "rpiq")}))
    return pd.DataFrame(recs)


