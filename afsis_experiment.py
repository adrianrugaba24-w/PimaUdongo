def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=None,
                    help="Real AfSIS Phase I root (<root>/Georeferences, "
                         "<root>/Wet_Chemistry). Omit to build the labelled "
                         "synthetic stand-in.")
    ap.add_argument("--synthetic", action="store_true",
                    help="Declare that the files at --root are NOT real AfSIS data "
                         "(a stand-in or hand-made fixture). Output is then labelled "
                         "synthetic. A stand-in written by synthetic_afsis.py is "
                         "detected automatically from its marker file, so this flag "
                         "is only needed for other fake data.")
    ap.add_argument("--data-dir", default="data/afsis_stand_in",
                    help="Where the synthetic stand-in is written (ignored with --root)")
    ap.add_argument("--target"); ap.add_argument("--features", nargs="+")
    ap.add_argument("--lat-col", dest="lat_col"); ap.add_argument("--lon-col", dest="lon_col")
    ap.add_argument("--country-col", dest="country_col")
    ap.add_argument("--ssn-col", dest="ssn_col"); ap.add_argument("--site-col", dest="site_id")
    ap.add_argument("--profile-col", dest="profile_id")
    ap.add_argument("--depth-from-col", dest="depth_from"); ap.add_argument("--depth-to-col",
                                                                             dest="depth_to")
    ap.add_argument("--countries", nargs="+",
                    help="Optional keep-only list; the Uganda subset is always reported "
                         "separately whether or not this is set")
    ap.add_argument("--target-units", default="auto", choices=["auto", "percent", "g_per_kg"])
    ap.add_argument("--depth-cm", type=float, default=A.DEPTH_TARGET_CM)
    ap.add_argument("--lab-dupes", default="first", choices=["first", "mean", "keep"])
    ap.add_argument("--blocks", type=int, default=10)
    ap.add_argument("--seeds", type=int, default=5, help="CV repeats (>=5 for reported SDs)")
    ap.add_argument("--seed0", type=int, default=20261104)
    ap.add_argument("--export", default="export")
    ap.add_argument("--out", default=None, help="Prefix for csv/png (default <export>/results)")
    ap.add_argument("--quick", action="store_true",
                    help="Fewer seeds/levels - for tests only, never for reported numbers")
    ap.add_argument("--list-columns", action="store_true")
    a = ap.parse_args(argv)
    t_start = time.time()

    # ---------- 1. data, with provenance ------------------------------------
    if a.root:
        root = Path(a.root)
        if not root.is_dir():
            sys.exit(f"--root {root} does not exist.")
        # A stand-in identifies itself by its marker file; --synthetic is the
        # human override for any other fake directory.  See classify_data_source.
        data_kind, real_data, marker = classify_data_source(root, a.synthetic)
        if marker:
            print(f"[data] marker {S.MARKER_NAME} found in {root}: output will be "
                  f"labelled SYNTHETIC and must not be cited.")
    else:
        root = Path(a.data_dir)
        info = S.write_dataset(root)
        print(f"[synthetic] stand-in written to {root}: {info}")
        print(f"[synthetic] {S.specification()['warning']}")
        # the marker just written is what makes this run self-identifying
        data_kind, real_data, marker = classify_data_source(root, a.synthetic)
    if not real_data:
        print("[data] NOT REAL AfSIS DATA - every number below describes a simulation.")

    df, manifest = A.load_raw(root)
    dversion = A.dataset_version(manifest)
    print(f"[data] {len(df)} merged rows from {len(manifest)} files | "
          f"dataset_version={dversion}")

    overrides = {}
    role_of = {"target": "target", "lat_col": "lat", "lon_col": "lon",
               "country_col": "country", "ssn_col": "ssn", "features": "features",
               "site_id": "site_id", "profile_id": "profile_id",
               "depth_from": "depth_from", "depth_to": "depth_to"}
    for attr, role in role_of.items():
        val = getattr(a, attr)
        if val:
            overrides[role] = val
    schema = A.detect_schema(df, overrides)
    if a.list_columns:
        print(f"country counts:\n{df[schema.country].value_counts().to_string()}"
              if schema.country else "(no country column)")
        print(f"\nall {len(df.columns)} columns:\n" + "\n".join(df.columns))
        print("\ndetected:", json.dumps(_jsonable(vars(schema)), indent=1, default=str))
        print("\nmissing % (top 20):\n",
              df.isnull().mean().sort_values(ascending=False).head(20).to_string())
        return

    cfg = dict(depth=a.depth_cm, target_units=a.target_units, lab_dupes=a.lab_dupes)
    d, log = A.clean(df, schema, cfg)
    if a.countries and schema.country:
        before = len(d)
        d = d[d[schema.country].isin(a.countries)].reset_index(drop=True)
        log.append(dict(step="country_filter", n_before=before, n_removed=before - len(d),
                        n_after=len(d), reason=f"kept only {a.countries}"))
    card = A.data_card(d, schema, log, FOCUS_COUNTRY)
    A.print_card(card, log, schema)
    if len(d) < 3 * V.FOLDS:
        sys.exit(f"Only {len(d)} usable rows - too few for {V.FOLDS}-fold CV. "
                 f"Check the cleaning ledger above and the column overrides.")

    units = card["target_units"]
    gk = schema.group_key()
    X0 = d[schema.features].to_numpy(float)
    y = d[schema.target].to_numpy(float)
    ids = d[gk].to_numpy()
    coords = d[[schema.lat, schema.lon]].to_numpy(float)
    # SOC is strictly positive and right-skewed at any unit, so the model works
    # on log1p and predictions are returned on the original scale.  If any
    # non-positive value survived cleaning, the log scale is off the table.
    log_target = bool(np.all(y > 0))
    print(f"[setup] {X0.shape[0]} rows x {X0.shape[1]} features | units={units} | "
          f"log-target={log_target} (decided from the inferred units, not tuned)")

    seeds = list(range(a.seed0, a.seed0 + max(1, a.seeds)))
    if a.quick:
        seeds = seeds[:2]
    row_groups, gdiag = V.spatial_groups(coords, ids, a.blocks, seeds[0])
    print(f"[folds] spatial blocking: {gdiag['blocks']} clusters over "
          f"{gdiag['n_sites']} sites; same folds reused for every model")

    specs = V.model_specs()
    # Scope of each sub-experiment.  --quick shrinks it so the test suite can
    # boot the whole pipeline in under a minute; the reduced scope is written
    # into results.json, so a quick artefact can never be mistaken for a
    # reported one.
    noise_levels = V.NOISE_LEVELS if not a.quick else [0.0, 0.5, 1.0]
    block_sizes = V.BLOCK_SIZES if not a.quick else [5, 10]
    noise_models = NOISE_SWEEP_MODELS if not a.quick else ("ridge", "gradient_boosting")
    # The secondary experiments (noise, control, blocks) keep the same fold
    # groups as E1; they only need enough seeds to show a trend, and E1 is the
    # number reported with a mean and an SD.
    n_sub = 2 if not a.quick else 1
    noise_seeds = block_seeds = ctrl_seeds = seeds[:n_sub]
    conf_seeds = seeds[:3] if not a.quick else seeds[:1]
    # E4b redraws the spatial partition once per seed, so it needs several seeds
    # to say anything about partition uncertainty.
    part_seeds = seeds if not a.quick else seeds[:2]
    part_models = ("random_forest", "ridge")
    part_summary: list[dict] = []
    plan = dict(quick=bool(a.quick), main_tune=not a.quick, main_seeds=len(seeds),
                noise_seeds=len(noise_seeds), noise_models=list(noise_models),
                noise_scheme="spatial",
                control_seeds=len(ctrl_seeds), block_seeds=len(block_seeds),
                partition_seeds=len(part_seeds), partition_models=list(part_models),
                partition_methods=["kmeans_seed", "grid_offset"],
                grid_target_groups=max(V.FOLDS + 1, int(a.blocks)),
                grid_cells_side=None,   # filled in by grid_resolution() during E4b
                grid_jobs=dict(random_forest=specs["random_forest"].grid_jobs,
                               gradient_boosting=specs["gradient_boosting"].grid_jobs),
                note=("Parallelism affects wall-clock only: every grid candidate is a "
                      "separate seeded fit, so R2 is identical at n_jobs=1 and n_jobs=4 "
                      "(checked). --quick additionally skips nested tuning; it is for "
                      "tests, never for reported numbers."))

    # ---------- 2. main comparison: random vs spatial, nested tuning --------
    print(f"[E1] random vs spatial CV, nested tuning={not a.quick}, "
          f"{len(seeds)} seeds ...")
    main_rows = V.sweep(X0, y, row_groups, specs, ["random", "spatial"], seeds,
                        log_target, None, tune=not a.quick, label="main")
    for e in [r for r in main_rows if "error" in r]:
        print(f"  !! FAILED cell {e['model']}/{e['cv']}/seed{e['seed']}: {e['error']}")
    params_by_key = {}
    for name in specs:
        for scheme in ("random", "spatial"):
            p = _mode_params(main_rows, name, scheme)
            if p:
                params_by_key[(name, scheme)] = p

    base_rmse = {r["cv"]: r["rmse_mean"] for r in main_rows
                 if r["model"] == "mean_baseline" and "rmse_mean" in r}
    gap_rows = []
    for name in specs:
        rr = next((r for r in main_rows if r["model"] == name and r["cv"] == "random"
                   and "per_seed" in r), None)
        rs = next((r for r in main_rows if r["model"] == name and r["cv"] == "spatial"
                   and "per_seed" in r), None)
        if rr and rs and len(rr["per_seed"]) == len(rs["per_seed"]):
            per = {p["seed"]: (p, s) for p, s in zip(rr["per_seed"], rs["per_seed"])}
            gaps = [v[0]["r2"] - v[1]["r2"] for v in per.values()]
            gap_rows.append(dict(model=name,
                                 r2_random=rr["r2_mean"], r2_spatial=rs["r2_mean"],
                                 gap_mean=float(np.mean(gaps)),
                                 gap_sd=float(np.std(gaps, ddof=1)) if len(gaps) > 1 else 0.0,
                                 rmse_random=rr["rmse_mean"], rmse_spatial=rs["rmse_mean"],
                                 spatial_beats_baseline=bool(rs["rmse_mean"] < base_rmse[rs["cv"]]),
                                 tuned_params=params_by_key.get((name, rs["cv"]))))

    # ---------- 3. noise sweep, both arms ----------------------------------
    # Spatial CV only: the question is how the headline (new-area) skill degrades
    # with sensor error, and doubling the schemes would double the cost without
    # changing the conclusion.
    print(f"[E2] sensor-noise sweep on {list(noise_models)} "
          f"(clean-train/noisy-test and noisy-train/noisy-test), spatial CV ...")
    sweep_specs = {k: specs[k] for k in noise_models}
    noise_rows = V.sweep(X0, y, row_groups, sweep_specs, ["spatial"], noise_seeds,
                         log_target, params_by_key, tune=False, label="noise",
                         noise_levels=noise_levels, arms=V.ARMS)

    # ---------- 4. shuffled-target control ---------------------------------
    print("[E3] shuffled-target control (must land near R2 = 0) ...")
    rng_shuf = np.random.default_rng(seeds[0])
    y_shuf = rng_shuf.permutation(y)
    shuffle_rows = V.sweep(X0, y_shuf, row_groups, specs, ["spatial"], ctrl_seeds,
                           log_target, params_by_key, tune=False, label="shuffled_control",
                           extra=dict(shuffle_seed=int(seeds[0])))

    # ---------- 5. block-size sensitivity ----------------------------------
    print("[E4] spatial block-size sensitivity ...")
    block_rows = []
    for nb in block_sizes:
        rg, dg = V.spatial_groups(coords, ids, nb, seeds[0])
        rows = V.sweep(X0, y, rg, {k: specs[k] for k in ("random_forest", "ridge")},
                       ["spatial"], block_seeds, log_target, params_by_key, tune=False,
                       label="block_sensitivity", extra=dict(blocks=int(dg["blocks"]),
                                                              n_clusters=len(dg["cluster_sizes"])))
        block_rows.extend(rows)

    # ---------- 5b. partition / boundary sensitivity ----------------------
    # E1 deliberately uses ONE partition for every model and seed: that is what
    # makes R2_random - R2_spatial a paired comparison.  The price is that the
    # seed-to-seed SD of a spatial cell measures learner randomness only, so it
    # is exactly 0.000 for deterministic models.  Two blocking families are
    # redrawn here, with the learner seed held constant so nothing but the
    # partition varies, and partitions are compared up to renumbering
    # (V.partition_signature) because cluster labels are arbitrary.
    #   kmeans - the reported blocking, same block count, different KMeans seed
    #   grid   - random rotation + random grid origin, so the boundaries move
    part_rows, grid_rows = [], []
    print(f"[E4b] partition sensitivity: {len(part_seeds)} KMeans seeds at "
          f"{a.blocks} blocks + {len(part_seeds)} grid-offset partitions, "
          f"models={list(part_models)} ...")
    sig_counts = {}
    for pb in part_seeds:
        rg, dg = V.spatial_groups(coords, ids, a.blocks, pb)
        sig_counts.setdefault(V.partition_signature(rg), []).append(int(pb))
        part_rows.extend(V.sweep(X0, y, rg, {k: specs[k] for k in part_models},
                                 ["spatial"], [seeds[0]], log_target, params_by_key,
                                 tune=False, label="partition_sensitivity",
                                 extra=dict(block_seed=int(pb), blocks=int(dg["blocks"]))))
    n_km = len(sig_counts)
    # The grid family needs its grain chosen from the DATA, not from a constant:
    # every partition must leave at least FOLDS + 1 non-empty cells so GroupKFold
    # has enough groups for every seed, and the grain should be comparable to the
    # reported --blocks.  grid_resolution() finds the smallest square grid that
    # works for ALL seeds, so the partitions being compared share one grain.
    gside = V.grid_resolution(coords, ids, max(V.FOLDS + 1, int(a.blocks)), part_seeds)
    plan["grid_cells_side"] = int(gside)
    print(f"  grid grain resolved from the data: {gside}x{gside} cells "
          f"(target >= {max(V.FOLDS + 1, int(a.blocks))} groups per partition)")
    sig_grid, grid_skipped = {}, []
    for pb in part_seeds:
        gg, gdg = V.grid_groups(coords, ids, gside, pb)
        n_cells = len(np.unique(gg))
        if n_cells < V.FOLDS + 1:
            # Honest skip: recorded in the finding rather than hidden.
            grid_skipped.append((int(pb), int(n_cells)))
            continue
        sig_grid.setdefault(V.partition_signature(gg), []).append(int(pb))
        grid_rows.extend(V.sweep(X0, y, gg, {k: specs[k] for k in part_models},
                                 ["spatial"], [seeds[0]], log_target, params_by_key,
                                 tune=False, label="boundary_sensitivity",
                                 extra=dict(block_seed=int(pb),
                                            blocks=int(gdg["blocks"]),
                                            cells_per_side=int(gdg["cells_per_side"]))))
    for e in [r for r in part_rows + grid_rows if "error" in r]:
        print(f"  !! FAILED cell {e['model']}/{e.get('experiment')}/"
              f"partition{e.get('block_seed')}: {e['error']}")
    part_summary += _spread(part_rows, part_models, "kmeans_seed",
                            int(seeds[0]), n_km, int(a.blocks))
    part_summary += _spread(grid_rows, part_models, "grid_offset",
                            int(seeds[0]), len(sig_grid), None)
    # The wording is built from what the two families did, so it cannot claim a
    # varied estimate when the partitions never changed.
    km_read = (
        "gave 1 distinct partition, so the reported k-means blocking is insensitive "
        "to its own seed and the 0.000 SD of the main table is a MEASURED NULL "
        "(the estimate did not move), not evidence that fold placement cannot matter"
        if n_km == 1 else
        f"gave {n_km} distinct partition(s), so part of the spatial-score spread is "
        f"fold-placement uncertainty"
    )
    gr = [p for p in part_summary if p["method"] == "grid_offset"]
    gr_txt = "; ".join(
        f"{p['model'].replace('_', ' ')} R2 {p['r2_mean']:.3f}"
        + (f" +/- {p['r2_sd']:.3f}" if p.get("r2_sd") else "")
        for p in gr)
    skip_txt = ("" if not grid_skipped else
                " [skipped: " + ", ".join(f"seed {s} -> only {n} cells"
                                          for s, n in grid_skipped)
                + f", below the {V.FOLDS + 1} groups needed]")
    partition_finding = (
        f"Family kmeans_seed: {len(part_seeds)} KMeans seeds at {a.blocks} blocks "
        f"(partitions compared up to cluster renumbering, which is arbitrary) "
        f"{km_read}. Family grid_offset: boundaries redrawn with a random rotation "
        f"and grid origin at a {gside}x{gside} grain, {len(part_seeds) - len(grid_skipped)} "
        f"seed run(s) -> {len(sig_grid)} distinct partition(s){skip_txt}; spread: "
        f"{gr_txt or 'not estimable'}. Both families are in "
        f"results.partition_sensitivity (per-partition rows in "
        f"results.partition_rows, learner seed held constant), and the effect of "
        f"the block COUNT is in results.block_sensitivity.")
    print(f"  finding: {partition_finding}")

    # ---------- 6. conformal interval under spatial CV --------------------
    best = max((r for r in gap_rows if r["model"] != "mean_baseline"),
               key=lambda r: r["r2_spatial"], default=None)
    interval = dict(note="no model available")
    if best:
        print(f"[E5] split-conformal interval, model={best['model']} ...")
        per_seed = [V.conformal_spatial(X0, y, row_groups, specs[best["model"]],
                                        params_by_key.get((best["model"], "spatial")),
                                        s, log_target) for s in conf_seeds]
        cov = [p["empirical_coverage"] for p in per_seed if p.get("empirical_coverage") is not None]
        wid = [p["mean_width"] for p in per_seed if p.get("mean_width") is not None]
        interval = dict(
            model=best["model"], nominal=V.NOMINAL_COVERAGE,
            empirical_coverage=float(np.mean(cov)) if cov else None,
            coverage_sd=float(np.std(cov, ddof=1)) if len(cov) > 1 else 0.0,
            mean_width=float(np.mean(wid)) if wid else None,
            half_width=float(np.mean(wid) / 2) if wid else None,
            median_target=float(np.median(y)),
            n_calibration_folds=sum(p.get("n_folds", 0) for p in per_seed),
            method=per_seed[0].get("method"),
            honest_note=("The nominal 90% interval is calibrated on held-out spatial "
                         "blocks and scored on test blocks never seen; coverage below "
                         "0.90 means the interval is too narrow for new areas."),
        )

    # ---------- 7. break-even noise ----------------------------------------
    # "How much sensor error before the model is no better than the field mean?"
    # Reported per arm for the model that actually runs in the noise sweep.
    break_even = {}
    # Prefer the headline model so the break-even sentence on the web page is
    # about the model that is actually deployed; fall back to whatever the sweep
    # ran when the headline model was excluded (--quick).
    be_model = next((m for m in ([best["model"]] if best else []) + list(noise_models)
                     if any(r.get("model") == m for r in noise_rows)), None)
    if be_model:
        schemes_seen = sorted({r["cv"] for r in noise_rows if r.get("model") == be_model})
        for arm in V.ARMS:
            for scheme in schemes_seen:
                cells = sorted({r["noise"] for r in noise_rows
                                if r.get("model") == be_model and r.get("cv") == scheme
                                and r.get("arm") == arm and "rmse_mean" in r})
                be = None
                for nl in cells:
                    r = next((x for x in noise_rows if x.get("model") == be_model
                              and x.get("cv") == scheme and x.get("arm") == arm
                              and x.get("noise") == nl and "rmse_mean" in x), None)
                    if r and r["rmse_mean"] >= base_rmse.get(scheme, float("inf")):
                        be = nl
                        break
                break_even[f"{arm}|{scheme}"] = be
        break_even["model"] = be_model

    # ---------- 8. write artefacts ----------------------------------------
    out_prefix = Path(a.out) if a.out else Path(a.export) / "results"
    out_prefix.parent.mkdir(parents=True, exist_ok=True)
    tidy = _tidy(main_rows + noise_rows + shuffle_rows + block_rows + part_rows + grid_rows)
    summary = tidy[tidy["seed"].isna()].copy()
    runs = tidy[tidy["seed"].notna()].copy()
    summary.to_csv(out_prefix.with_name(out_prefix.name + "_summary.csv"), index=False)
    runs.to_csv(out_prefix.with_name(out_prefix.name + "_runs.csv"), index=False)

    ranges = {f: dict(p5=float(np.nanpercentile(d[f], 5)), p95=float(np.nanpercentile(d[f], 95)),
                      min=float(np.nanmin(d[f])), max=float(np.nanmax(d[f])),
                      median=float(np.nanmedian(d[f])), sd=float(np.nanstd(d[f])))
              for f in schema.features}
    # Physical limits, identical to the ones the cleaning pass used, so the API
    # can reject an impossible reading instead of extrapolating from it.
    feature_bounds, feature_units = {}, {}
    for f in schema.features:
        b = A._bounds_for(f, units)
        feature_bounds[f] = [b[0], b[1]] if b else [None, None]
        feature_units[f] = ("percent (g/100 g)" if b == A.BOUNDS["percent"] else
                            "dimensionless" if b == A.BOUNDS["ph"] else
                            "dS/m" if b == A.BOUNDS["ec"] else "unknown")

    payload = dict(
        schema_version=2,
        generated_at_utc=_dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"),
        runtime_seconds=round(time.time() - t_start, 1),
        command=" ".join(["python afsis_experiment.py"] + (argv or sys.argv[1:])),
        git_commit=A.git_version(),
        package_versions=A.package_versions(),
        data=dict(
            kind=data_kind, is_real_data=real_data, root=str(root),
            stand_in_marker=bool(marker),
            dataset_version=dversion, files=manifest,
            licence=AFSIS_LICENCE if real_data else SYNTHETIC_LICENCE,
            synthetic_specification=S.specification() if not real_data else None,
            cleaning_log=log, data_card=card, depth_rule=dict(target_cm=a.depth_cm,
                                                              applied=any(l.get("applied") for l in log
                                                                          if l["step"] == "depth_selection")),
            units=units, units_basis=next((l.get("units_basis") for l in log
                                           if "units_basis" in l), None),
        ),
        target=dict(name=schema.target, units=units, log_transform=bool(log_target),
                    column_detection=schema.origin.get("target")),
        features=list(schema.features),
        feature_ranges=ranges,
        feature_bounds=feature_bounds,
        feature_units=feature_units,
        blocked_as_features=schema.unmatched,
        validation=dict(folds=V.FOLDS, inner_folds=V.INNER_FOLDS, seeds=seeds,
                        n_seeds=len(seeds), blocks=int(a.blocks),
                        spatial_grouping=("KMeans on per-site coordinate centroids -> "
                                          "GroupKFold; records of one site/profile "
                                          "always share a fold"),
                        group_column=gk, blocking_diagnostics=gdiag,
                        tuning=("GridSearchCV inside every training fold (nested CV); "
                                "imputation and scaling fitted on training folds only"),
                        metrics=dict(r2="pooled out-of-fold, original target scale",
                                     rmse="pooled out-of-fold", mae="pooled out-of-fold",
                                     rpiq="IQR(y)/RMSE, Bellon-Maurel et al. 2010"),
                        noise_levels=noise_levels, noise_arms=list(V.ARMS),
                        block_sizes=[int(b) for b in block_sizes],
                        spatial_partition_note=(
                            "The main comparison builds the spatial partition ONCE (KMeans "
                            "seeded with --seed0) and reuses it for every model, seed and "
                            "scheme, so random-vs-spatial is a paired comparison. The SD "
                            "across seeds of a spatial-CV cell therefore measures learner "
                            "randomness only and is exactly 0.000 for deterministic models "
                            "(ridge, PLS). The two uncertainties the fixed partition hides "
                            "are reported separately: where the block boundaries fall "
                            "(results.partition_sensitivity, methods kmeans_seed and "
                            "grid_offset) and how many blocks are used "
                            "(results.block_sensitivity). " + partition_finding),
                        experiment_scope=plan),
        results=dict(main=[{k: v for k, v in r.items() if k != "per_seed"} for r in main_rows],
                     validation_gap=gap_rows,
                     noise_sweep=[{k: v for k, v in r.items() if k != "per_seed"} for r in noise_rows],
                     shuffled_control=[{k: v for k, v in r.items() if k != "per_seed"} for r in shuffle_rows],
                     block_sensitivity=[{k: v for k, v in r.items() if k != "per_seed"} for r in block_rows],
                     partition_sensitivity=part_summary,
                     partition_rows=[{k: v for k, v in r.items() if k != "per_seed"}
                                     for r in part_rows + grid_rows],
                     baseline_rmse=base_rmse,
                     interval=interval),
        headline=dict(model=best["model"] if best else None,
                      r2_spatial=best["r2_spatial"] if best else None,
                      rmse_spatial=best["rmse_spatial"] if best else None,
                      r2_random=best["r2_random"] if best else None,
                      validation_gap=best["gap_mean"] if best else None,
                      beats_field_mean_spatially=bool(best["spatial_beats_baseline"]) if best else None,
                      break_even_noise=break_even),
        limitations=LIMITATIONS,
        model_version=None,      # filled in below, after the model bytes exist
    )

    # ---------- 9. the deployed model + its metadata -----------------------
    export_dir = Path(a.export)
    export_dir.mkdir(parents=True, exist_ok=True)
    final_name = best["model"] if best else "random_forest"
    final_params = params_by_key.get((final_name, "spatial"))
    final = V.apply_params(V.build_pipeline(specs[final_name], log_target, seeds[0]), final_params)
    final.fit(X0, y)
    buf = io.BytesIO()
    joblib.dump(final, buf)
    model_bytes = buf.getvalue()
    payload["model_version"] = "sha256:" + hashlib.sha256(model_bytes).hexdigest()[:16]
    payload["model_file"] = "model.joblib"
    payload["training_data_version"] = dversion

    results_txt = json.dumps(_jsonable(payload), indent=1)
    (export_dir / "results.json").write_text(results_txt)
    # Hash the file exactly as written, so the API can detect any drift between
    # the model and the numbers it is supposed to report.
    results_sha = hashlib.sha256((export_dir / "results.json").read_bytes()).hexdigest()
    (export_dir / "model.joblib").write_bytes(model_bytes)
    (export_dir / "model_meta.json").write_text(json.dumps(_jsonable(dict(
        model_version=payload["model_version"],
        model_kind=type(final.named_steps["model"] if hasattr(final, "named_steps")
                        else final).__name__,
        pipeline_steps=[s for s, _ in final.steps],
        feature_names=list(schema.features),
        target_name=schema.target, target_units=units, log_target=bool(log_target),
        training_data_version=dversion,
        training_data_sha256=hashlib.sha256(
            "".join(m["sha256"] for m in manifest).encode()).hexdigest() if manifest else None,
        n_rows=int(len(d)), results_sha256=results_sha,
        model_params=_jsonable(final_params), model_seed=int(seeds[0]),
        sklearn_version=A.package_versions()["scikit-learn"],
        fitted_at_utc=payload["generated_at_utc"],
    )), indent=1))

    _plot(out_prefix, main_rows, noise_rows, block_rows, interval, base_rmse, gap_rows,
          part_summary)

    # ---------- 10. console summary ---------------------------------------
    print("\n=== HEADLINE (spatial CV first) ===")
    if not gap_rows:
        print("  no model completed the main comparison - see the FAILED cells above")
    for r in sorted(gap_rows, key=lambda x: -(x["r2_spatial"] if np.isfinite(x["r2_spatial"]) else -9)):
        print(f"  {r['model']:18s} R2 spatial={r['r2_spatial']:+.3f}  random={r['r2_random']:+.3f}  "
              f"gap={r['gap_mean']:+.3f}+/-{r['gap_sd']:.3f}  RMSE spat={r['rmse_spatial']:.3f} "
              f"({units})  beats field mean: {r['spatial_beats_baseline']}")
    print(f"  field-mean RMSE: spatial={base_rmse['spatial']:.3f} random={base_rmse['random']:.3f}")
    if isinstance(interval, dict) and interval.get("empirical_coverage") is not None:
        print(f"  conformal: nominal {interval['nominal']:.0%} -> empirical coverage under "
              f"spatial CV = {interval['empirical_coverage']:.3f} "
              f"(width {interval['mean_width']:.2f} {units})")
    sc = {r["model"]: r["r2_mean"] for r in shuffle_rows if r["cv"] == "spatial"}
    print(f"  shuffled-target control R2: "
          f"{ {k: round(v, 3) for k, v in sc.items()} }  (must be near 0)")
    print(f"  break-even noise ({break_even.get('model', 'n/a')}): "
          f"{ {k: v for k, v in break_even.items() if k != 'model'} }")
    for p in part_summary:
        sd = f"+/-{p['r2_sd']:.3f}" if p["r2_sd"] else "+/-0.000"
        print(f"  partition sensitivity ({p['model']}, {p['method']}, "
              f"{p['n_partitions']} seeds -> {p['distinct_partitions']} distinct "
              f"partition(s)): R2 spatial {p['r2_mean']:.3f} {sd} "
              f"[range {p['r2_min']:.3f}-{p['r2_max']:.3f}]")
    print(f"  wrote {export_dir}/results.json, model.joblib, model_meta.json, "
          f"{out_prefix.name}_summary.csv, _runs.csv, _plot.png in "
          f"{time.time() - t_start:.1f}s")
    if not real_data:
        print("\n" + "=" * 68)
        print("SYNTHETIC STAND-IN RUN - these numbers validate the PIPELINE only.")
        print("They are not results about African soils and must not be cited.")
        print("=" * 68)


def _plot(prefix, main_rows, noise_rows, block_rows, interval, base_rmse, gap_rows,
          part_summary=()):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception as ex:
        print("Plot skipped:", ex)
        return
    fig, ax = plt.subplots(2, 2, figsize=(11, 8))

    # (a) R2 vs noise, both arms, spatial CV
    a = ax[0, 0]
    for model in NOISE_SWEEP_MODELS:
        for arm, style in zip(V.ARMS, ("-", "--")):
            pts = sorted([(r["noise"], r["r2_mean"]) for r in noise_rows
                          if r["model"] == model and r["cv"] == "spatial" and r["arm"] == arm])
            if pts:
                a.plot([p[0] for p in pts], [p[1] for p in pts], style, marker="o", ms=4,
                       label=f"{model}, {arm}")
    a.axhline(0, color="k", lw=0.8)
    a.set_xlabel("sensor noise (x training-fold feature SD)")
    a.set_ylabel("R2 (spatial CV)"); a.set_title("R2 vs input noise"); a.legend(fontsize=6)

    # (b) validation gap
    b = ax[0, 1]
    names = [g["model"] for g in gap_rows]
    br = np.arange(len(names))
    b.bar(br - 0.2, [g["r2_random"] for g in gap_rows], 0.4, label="random CV")
    b.bar(br + 0.2, [g["r2_spatial"] for g in gap_rows], 0.4, label="spatial CV")
    b.set_xticks(br); b.set_xticklabels(names, rotation=30, ha="right", fontsize=7)
    b.axhline(0, color="k", lw=0.8); b.legend(fontsize=7)
    b.set_ylabel("R2"); b.set_title("Validation gap: random vs spatial CV")

    # (c) block sensitivity + partition uncertainty
    c = ax[1, 0]
    for model in {r["model"] for r in block_rows}:
        pts = sorted([(r["blocks"], r["r2_mean"]) for r in block_rows if r["model"] == model])
        if pts:
            c.plot([p[0] for p in pts], [p[1] for p in pts], marker="o", ms=4, label=model)
    for p in part_summary:
        if p["blocks"] is None or not p.get("r2_sd"):   # grid cells are not a block count
            continue
        c.errorbar([p["blocks"]], [p["r2_mean"]], yerr=[p["r2_sd"]], fmt="none",
                       ecolor="k", capsize=4, lw=1.3, label=f"{p['model']} +/- partition SD")
    lines = [f"{p['method']}: {p['model'].replace('_', ' ')} "
             f"{p['r2_mean']:.3f} +/- {(p['r2_sd'] or 0.0):.3f} "
             f"({p['distinct_partitions']} distinct partition(s))"
             for p in part_summary]
    if lines:
        c.annotate("\n".join(lines), xy=(0.02, 0.03), xycoords="axes fraction", fontsize=6,
                   va="bottom")
    c.set_xscale("log"); c.set_xlabel("spatial blocks"); c.set_ylabel("R2 (spatial CV)")
    c.set_title("Block size, and the SD from redrawing the blocks")
    c.legend(fontsize=7)

    # (d) coverage
    d_ = ax[1, 1]
    if isinstance(interval, dict) and interval.get("empirical_coverage") is not None:
        d_.bar(["nominal", "empirical\n(spatial CV)"],
               [interval["nominal"], interval["empirical_coverage"]], color=["#888", "#c5671a"])
        d_.set_ylim(0, 1.05); d_.set_ylabel("coverage")
        d_.set_title(f"90% interval: measured coverage "
                     f"{interval['empirical_coverage']:.2f}")
        for i, v in enumerate([interval["nominal"], interval["empirical_coverage"]]):
            d_.text(i, v + 0.02, f"{v:.2f}", ha="center", fontsize=8)
    else:
        d_.text(0.5, 0.5, "interval not computed\n(not enough data)", ha="center")
        d_.set_axis_off()

    fig.tight_layout()
    fig.savefig(prefix.with_name(prefix.name + "_plot.png"), dpi=140)
    plt.close(fig)
    print("Saved plot.")


if __name__ == "__main__":
    main()
